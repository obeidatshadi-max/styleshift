// Language context
// ---------------------------------------------------------------------------
interface LangContextValue {
  lang: Lang
  dir: 'ltr' | 'rtl'
  setLang: (l: Lang) => void
  toggle: () => void
  /** Text for the current language. */
  dict: Dict
}

const LangContext = createContext<LangContextValue | null>(null)

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>('en')
  const [dict, setDict] = useState<Dict>(EN)

  // Switch only once the dictionary is in memory, so the screen never shows raw keys.
  const apply = useCallback((l: Lang) => {
    if (l === 'en') { setDict(EN); setLangState('en'); return }
    loadArabic().then(d => { setDict(d); setLangState('ar') }).catch(() => { arLoading = null })
  }, [])

  // Hydrate from localStorage after mount (server renders 'en' to avoid mismatch)
  useEffect(() => {
    const saved = (typeof window !== 'undefined' && localStorage.getItem(STORAGE_KEY)) as Lang | null
    if (saved === 'ar' || saved === 'en') apply(saved)
  }, [apply])

  // Reflect language on <html> and persist
  useEffect(() => {
    const dir = lang === 'ar' ? 'rtl' : 'ltr'
    document.documentElement.lang = lang
    document.documentElement.dir = dir
    try { localStorage.setItem(STORAGE_KEY, lang) } catch { /* ignore */ }
  }, [lang])

  const setLang = useCallback((l: Lang) => apply(l), [apply])
  const toggle = useCallback(() => apply(lang === 'en' ? 'ar' : 'en'), [apply, lang])

  const dir = lang === 'ar' ? 'rtl' : 'ltr'
  return (
    <LangContext.Provider value={{ lang, dir, setLang, toggle, dict }}>
      {children}
    </LangContext.Provider>
  )
}

export function useLang(): LangContextValue {
  const ctx = useContext(LangContext)
  if (!ctx) throw new Error('useLang must be used within LanguageProvider')
  return ctx
}

/** Returns a translator bound to the current language. */
export function useT() {
  const { dict } = useLang()
  return useCallback(
    (key: string, params?: Record<string, string | number>) => format(dict[key] ?? key, params),
    [dict]
  )
}

/** Localized display label for a badge (badges are stored in DB by English name). */
export function useBadgeLabel() {
  const { dict } = useLang()
  return useCallback((badge: BadgeName) => dict[`badge.${badge}`] ?? badge, [dict])
}

/** Style names and order for the current language. Light: login and landing use it without pulling
 * in the game levels or SPS text. Game screens use useGameData / useSpsData from '@/lib/i18n-game'. */
export function useStyleData() {
  const { lang } = useLang()
  return lang === 'ar' ? { STYLES: STYLES_AR, STYLE_ORDER } : { STYLES, STYLE_ORDER }
}
