// @vitest-environment jsdom
import { afterEach, describe, expect, it, vi } from 'vitest'
import { cleanup, fireEvent, render, screen } from '@testing-library/react'
import { LanguageProvider } from '@/lib/i18n'
import RecordedConversationAnalysis from './RecordedConversationAnalysis'
const m = vi.hoisted(() => ({ saved: vi.fn() }))
vi.mock('@/hooks/useSavedReport', () => ({ useSavedReport: m.saved }))
vi.mock('@/components/report/ConversationReport', () => ({ ConversationReport: ({ report, outdated }: { report: { label: string }; outdated: boolean }) => <p>{report.label}{outdated ? ' [outdated]' : ''}</p> }))
afterEach(() => { cleanup(); vi.unstubAllGlobals(); vi.clearAllMocks(); localStorage.clear() })
describe('two-person recorder AI analysis', () => {
  it('does not analyze until requested, then sends the existing session and renders the report', async () => {
    m.saved.mockReturnValue({ status: 'missing' })
    const fetch = vi.fn().mockResolvedValue(Response.json({ report: { label: 'Iraqi report with original evidence' } }))
    vi.stubGlobal('fetch', fetch)
    render(<LanguageProvider><RecordedConversationAnalysis sessionId="recorded-session" /></LanguageProvider>)
    expect(fetch).not.toHaveBeenCalled()
    expect(m.saved).not.toHaveBeenCalled()
    expect((screen.getByRole('button', { name: 'AI conversation analysis' }) as HTMLButtonElement).disabled).toBe(true)
    fireEvent.click(screen.getByRole('checkbox', { name: /Both participants agree/ }))
    fireEvent.click(screen.getByRole('button', { name: 'AI conversation analysis' }))
    await screen.findByText('Iraqi report with original evidence')
    expect(fetch).toHaveBeenCalledTimes(1)
    expect(JSON.parse(fetch.mock.calls[0][1].body)).toEqual({ sessionType: 'human_partner', sessionId: 'recorded-session', lang: 'en', analysisConsent: true })
  })
  it('reuses an existing saved report rather than generating another one', async () => {
    m.saved.mockReturnValue({ status: 'found', report: { label: 'Saved analysis' } })
    const fetch = vi.fn(); vi.stubGlobal('fetch', fetch)
    render(<LanguageProvider><RecordedConversationAnalysis sessionId="saved-session" /></LanguageProvider>)
    expect((screen.getByRole('button', { name: 'AI conversation analysis' }) as HTMLButtonElement).disabled).toBe(true)
    fireEvent.click(screen.getByRole('checkbox', { name: /Both participants agree/ }))
    fireEvent.click(screen.getByRole('button', { name: 'AI conversation analysis' }))
    await screen.findByText('Saved analysis')
    expect(fetch).not.toHaveBeenCalled()
  })
  it('marks the saved report outdated after a transcript correction and creates it again on request', async () => {
    m.saved.mockReturnValue({ status: 'found', report: { label: 'Saved analysis', transcriptVersion: 1 } })
    const fetch = vi.fn().mockImplementation(async (url: string) => {
      if (url.startsWith('/api/transcript-segments?')) return Response.json({ transcriptVersion: 1, canProposePhrases: false, segments: [{ segmentIndex: 0, speakerRole: 'rep', text: 'عندك وكت' }] })
      if (url === '/api/transcript-segments/correct') return Response.json({ newTranscriptVersion: 2 })
      return Response.json({ report: { label: 'Fresh analysis' } })
    })
    vi.stubGlobal('fetch', fetch)
    render(<LanguageProvider><RecordedConversationAnalysis sessionId="s" /></LanguageProvider>)
    fireEvent.click(screen.getByRole('checkbox', { name: /Both participants agree/ }))
    fireEvent.click(screen.getByRole('button', { name: 'AI conversation analysis' }))
    await screen.findByText('Saved analysis')
    fireEvent.click(screen.getByRole('button', { name: 'Check the transcript' }))
    fireEvent.change(await screen.findByDisplayValue('عندك وكت'), { target: { value: 'عندك وقت' } })
    fireEvent.click(screen.getByRole('button', { name: 'Save corrections' }))
    await screen.findByText('Saved analysis [outdated]')
    expect(fetch.mock.calls.some(c => c[0] === '/api/reports/generate')).toBe(false)
    fireEvent.click(screen.getByRole('button', { name: 'Create the analysis again from the corrected text' }))
    await screen.findByText('Fresh analysis')
    expect(fetch.mock.calls.filter(c => c[0] === '/api/reports/generate')).toHaveLength(1)
  })
  it('sends the partial-visit flag and shows the coach before the full report', async () => {
    const { groundCoach } = await import('@/lib/conversation-coach/ground')
    const { SYNTHETIC_EN, SYNTHETIC_EN_MODEL_OUTPUT } = await import('@/lib/conversation-coach/fixtures')
    const coach = groundCoach(SYNTHETIC_EN_MODEL_OUTPUT, SYNTHETIC_EN, { lang: 'en', partialRecording: true, transcriptQuality: null, delivery: null })
    m.saved.mockReturnValue({ status: 'missing' })
    const fetch = vi.fn().mockImplementation(async (url: string) => url === '/api/reports/generate'
      ? Response.json({ report: { label: 'Full report body', coach } })
      : Response.json({ recordings: 0, partialRecordings: 0, keys: [], practice: { attempts: 0, criterionMet: 0 } }))
    vi.stubGlobal('fetch', fetch)
    render(<LanguageProvider><RecordedConversationAnalysis sessionId="p" audioUrl="blob:local" /></LanguageProvider>)
    fireEvent.click(screen.getByRole('checkbox', { name: /only part of the visit/ }))
    fireEvent.click(screen.getByRole('checkbox', { name: /Both participants agree/ }))
    fireEvent.click(screen.getByRole('button', { name: 'AI conversation analysis' }))
    await screen.findByText('Key moments')
    const gen = fetch.mock.calls.find(c => c[0] === '/api/reports/generate')!
    expect(JSON.parse(gen[1].body).partialRecording).toBe(true)
    // Quotes are the transcript's own words; replay is offered because local audio exists.
    expect(screen.getAllByText(/My concern is patients stopping because of side effects/).length).toBeGreaterThan(0)
    expect(screen.getAllByRole('button', { name: /Replay this moment/ }).length).toBe(2)
    expect(screen.getByText('Replay practice')).toBeTruthy()
    // The full report is one tap away, not shown first.
    expect(screen.queryByText('Full report body')).toBeNull()
    fireEvent.click(screen.getByRole('button', { name: 'Show the full analysis' }))
    expect(screen.getByText('Full report body')).toBeTruthy()
  })
})
