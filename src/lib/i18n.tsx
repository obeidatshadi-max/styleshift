// Arabic loads on demand (./i18n-ar). Started as soon as this module runs in a browser whose
// saved language is Arabic, so it usually arrives before React hydrates.
let arDict: Dict | null = null
let arLoading: Promise<Dict> | null = null
function loadArabic(): Promise<Dict> {
  if (arDict) return Promise.resolve(arDict)
  arLoading ??= import('./i18n-ar').then(m => (arDict = m.default))
  return arLoading
}
/** Start loading the Arabic text early (e.g. before a language switch, or in tests). */
export function preloadArabic(): Promise<Dict> { return loadArabic() }

try {
  if (typeof window !== 'undefined' && localStorage.getItem(STORAGE_KEY) === 'ar') void loadArabic().catch(() => { arLoading = null })
} catch { /* storage blocked */ }

function format(str: string, params?: Record<string, string | number>): string {
  if (!params) return str
  return str.replace(/\{(\w+)\}/g, (_, k) => String(params[k] ?? ''))
}

